// Builds WIGGLE_BOX_GAME_MATRIX.md from test-results/results.json (written by every `npx playwright test` run).
// A cell is PASS only if every test behind it passed in that run; FAIL if any failed; NOT TESTED if none ran.
// Usage: node tools/matrix.mjs [results.json]
import { readFileSync, writeFileSync } from 'node:fs';

const KEYS = ['atoms', 'balance', 'bridge', 'cannon', 'chance', 'circuit', 'bubbles', 'paint', 'feed', 'shapes', 'music', 'words',
  'fireworks', 'forge', 'potion', 'geo', 'graph', 'art', 'laser', 'physics', 'primes', 'puzzles', 'robo', 'sand', 'space', 'splash', 'trace', 'waves'];
const NAMES = ['Atom Builder', 'Balance Scale', 'Bridge Builder', 'Cannon Launch', 'Chance Machine', 'Circuit Lab', 'Bubble Pop', 'Magic Paint',
  'Hungry Monster', 'Shape Sorter', 'Rainbow Piano', 'Word Builder', 'Firework Sky', 'Number Forge', 'Potion Lab', 'Shape Lab', 'Graph Rider',
  'Math Art', 'Laser Lab', 'Physics Lab', 'Prime Garden', 'Puzzle Box', 'Robo Code', 'Element Box', 'Space Orbits', 'Splash Lab', 'Letter Trace', 'Wave Lab'];
/* baseline defect tests → game */
const DGAME = { D03: 'shapes', D04: 'shapes', D05: 'bridge', D06: 'circuit', D07: 'circuit', D08: 'circuit', D09: 'balance', D10: 'balance', D11: 'robo', D12: 'robo',
  D13: 'geo', D14: 'art', D15: 'chance', D16: 'laser', D17: 'puzzles', D18: 'waves', D19: 'space' };
const TOUCH = { paint: 'Paint', shapes: 'Shape Sorter', sand: 'Element Box', physics: 'Physics Lab', circuit: 'Circuit Lab' };
const TURN = ['cannon', 'bridge', 'robo', 'physics', 'space', 'splash', 'laser', 'waves'];

// Several results files can be given: the first is the full run; later ones are reruns of single tests or projects.
// A test that ran again later takes the later result and is marked as a rerun, so the matrix says so.
const files = process.argv.slice(2).length ? process.argv.slice(2) : ['test-results/results.json'];
const res = JSON.parse(readFileSync(files[0], 'utf8'));
const byKey = new Map();
files.forEach((f, fi) => {
  const r = JSON.parse(readFileSync(f, 'utf8'));
  (function walk(s, path) { for (const x of s.suites || []) walk(x, [...path, x.title]); for (const sp of s.specs || []) for (const t of sp.tests) {
    const status = t.results.length ? t.results[t.results.length - 1].status : 'skipped';
    if (fi > 0 && status === 'skipped') continue;
    const k = `${sp.file}|${sp.title}|${t.projectName}`, prev = byKey.get(k);
    byKey.set(k, { file: sp.file || path[0], path, title: sp.title, project: t.projectName, status, ok: t.status === 'expected' || t.status === 'flaky', flaky: t.status === 'flaky', rerun: fi > 0, firstStatus: prev ? prev.status : null });
  } })(r, []);
});
const runs = [...byKey.values()].filter(r => r.status !== 'skipped' || !r.rerun);

const cell = list => { const ran = list.filter(r => r.status !== 'skipped'); if (!ran.length) return list.length ? 'NOT RUN' : 'NOT TESTED'; const re = ran.filter(r => r.rerun).length;
  return ran.every(r => r.ok) ? `PASS (${ran.length}${re ? `, ${re} rerun` : ''})` : `FAIL (${ran.filter(r => !r.ok).length}/${ran.length})`; };
const rows = KEYS.map((k, i) => {
  const num = String(i + 1).padStart(2, '0'), name = NAMES[i];
  const play = runs.filter(r => r.project === 'desktop' && r.path.some(p => p === `${num} ${name}` || p.startsWith(`${num} ${name} `)));
  const launch = runs.filter(r => r.project === 'desktop' && (r.title === `launch, render, exit and reenter: ${k}` || r.title === `no leaked frames or listeners after leaving mid-animation: ${k}`));
  const defects = runs.filter(r => r.project === 'desktop' && /^D\d\d/.test(r.title) && DGAME[r.title.slice(0, 3)] === k);
  const layout = runs.filter(r => r.project !== 'desktop' && (r.title === `@layout ${k}: controls reachable, play area usable` || (TOUCH[k] && r.title.startsWith(`@layout ${TOUCH[k]}:`)) || (TURN.includes(k) && r.title.startsWith('@layout turning'))));
  const offline = runs.filter(r => r.title.startsWith('after one visit') || (k === 'physics' && r.title.startsWith('if the physics engine cannot load')));
  const all = [...play, ...launch, ...defects, ...layout, ...offline];
  return { num, name, k, play: cell(play), launch: cell(launch), defects: defects.length ? cell(defects) : 'N/A', layout: cell(layout), offline: cell(offline), overall: all.length && all.every(r => r.ok) ? 'PASS' : all.some(r => !r.ok && r.status !== 'skipped') ? 'FAIL' : 'NOT TESTED', tests: play.map(r => r.title) };
});
const shared = runs.filter(r => (r.project === 'desktop' || r.project === 'perf') && (/0[02]-|17-|18-/.test(r.file) || /^D0[12]/.test(r.title)) && !/^launch, render|^no leaked frames/.test(r.title));
const total = runs.length, passed = runs.filter(r => r.ok).length, flaky = runs.filter(r => r.flaky).length;
const reruns = runs.filter(r => r.rerun);

let md = `# Wiggle Box game matrix

Generated by \`node tools/matrix.mjs\` from the full test run of ${res.stats ? new Date(res.stats.startTime).toISOString().slice(0, 16).replace('T', ' ') + ' UTC' : ''}${files.length > 1 ? ' and the follow-up runs noted below' : ''}.
**PASS** means every test behind that cell passed in this run; the number in brackets is how many tests. **FAIL** gives
failed/total. **N/A**: no baseline defect was filed for that game. Nothing is marked PASS without a test.

All tests: ${passed} of ${total} passed${flaky ? ` (${flaky} only on retry)` : ''}.
${reruns.length ? `Of these, ${reruns.length} come from a separate run after the full run: ${[...new Set(reruns.map(r => r.project === 'perf' ? 'the six timing tests (they run last, alone, and only start when everything else passed)' : `"${r.title}" (${r.firstStatus === 'timedOut' ? 'it ran out of time in the full run; given more time, it passed' : `full run: ${r.firstStatus}`})`))].join('; ')}.` : ''}

Columns:
- **Gameplay & science**: the game's own tests on desktop (every level or mode played through real input, results checked against independent calculations).
- **Launch & leaks**: opens, draws, closes, reopens; no frames, timers or listeners left behind after leaving mid-animation.
- **Baseline defects**: the D-tests that failed on the original code.
- **Touch screens**: phone and tablet, portrait and landscape (controls reachable, play area big enough, real finger input where listed, turning mid-game where listed).
- **Offline**: plays after the network is cut (service worker installed).

| # | Game | Gameplay & science | Launch & leaks | Baseline defects | Touch screens | Offline | Overall |
|---|---|---|---|---|---|---|---|
${rows.map(r => `| ${r.num} | ${r.name} | ${r.play} | ${r.launch} | ${r.defects} | ${r.layout} | ${r.offline} | **${r.overall}** |`).join('\n')}

Shared behaviour (all games): ${cell(shared)} — lifecycle sequences, rapid switching, browser Back, Escape, hidden-tab pause, storage
corruption and blocked storage, the service worker version stamp, offline update, 30/60/120 Hz speed, memory over many visits,
frame cost, stress runs, and baseline defects D01–D02.

## What each game's gameplay tests cover

${rows.map(r => `**${r.num} ${r.name}**\n${r.tests.map(t => `- ${t}`).join('\n') || '- (none)'}`).join('\n\n')}
`;
writeFileSync('WIGGLE_BOX_GAME_MATRIX.md', md);
console.log(rows.map(r => `${r.num} ${r.name.padEnd(15)} ${r.overall}`).join('\n'));
console.log(`total ${total}, passed ${passed}, flaky ${flaky}`);
